/** Generate a 90-day price history with realistic drift and occasional sales. */
function generateHistory(
  basePrice: number,
  daysBack = 90,
  volatility = 0.03,
): Array<{ date: string; price: number }> {
  const points: Array<{ date: string; price: number }> = [];
  const now = new Date();
  let price = basePrice * (1 + (Math.random() * 0.06 - 0.03)); // start slightly off base

  for (let d = daysBack; d >= 0; d -= 3) {
    const date = new Date(now);
    date.setDate(date.getDate() - d);
    // Random walk with mean reversion
    const shock = (Math.random() - 0.5) * 2 * volatility;
    const reversion = (basePrice - price) * 0.05;
    price = Math.round((price + price * shock + reversion) / 100) * 100;
    price = Math.max(basePrice * 0.85, Math.min(basePrice * 1.12, price));
    points.push({ date: date.toISOString().slice(0, 10), price });
  }
  return points;
}

